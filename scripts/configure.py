#!/usr/bin/env python3
"""Validate experiment settings and update the shared header only when changed."""
import os
from pathlib import Path
import re
import sys

SETTINGS = {"RADIO_FREQ_MHZ": (2440, 2360, 2500),
            "TX_PACKET_COUNT": (10000, 0, 0xfffffff0),
            "APP_PAYLOAD_SIZE": (32, 32, 247),
            "RUN_ID": (1, 0, 0xffffffff)}
FIELDS = {"RADIO_FREQ_MHZ": "freq_mhz", "TX_INTERVAL_MS": "tx_interval_ms",
          "TX_PACKET_COUNT": "packet_target", "APP_PAYLOAD_SIZE": "payload_bytes",
          "TX_INTERVAL_US": "tx_interval_us", "RUN_ID": "run_tag"}
IMAGE_PROFILES = {"baseline": 1500, "1200": 1200, "1100": 1100, "limit": 1044, "max": 0}
CONTROL_PROFILES = ("baseline", "balanced", "aggressive")

def integer(name, value, low, high):
    if not re.fullmatch(r"0|[1-9][0-9]*", value) or not low <= int(value) <= high:
        raise ValueError(f"{name} must be a decimal integer in [{low}, {high}]")
    return int(value)

def minimum_interval(payload):
    return (payload + 16) * 4 + 20

def configuration(environ):
    image_mode = integer("IMAGE_MODE", environ.get("IMAGE_MODE", "0"), 0, 1)
    control = environ.get("CONTROL_PROFILE", "baseline")
    if control not in CONTROL_PROFILES:
        raise ValueError("Unknown CONTROL_PROFILE")
    if not image_mode and control != "baseline":
        raise ValueError("Control profiles require image mode")
    values = {name: integer(name, environ.get(name, str(default)), low, high)
              for name, (default, low, high) in SETTINGS.items()}
    # Make exports unset optional variables as empty strings.
    ms, us = environ.get("TX_INTERVAL_MS"), environ.get("TX_INTERVAL_US")
    if ms:
        ms = integer("TX_INTERVAL_MS", ms, 1, 60000)
    if us:
        us = integer("TX_INTERVAL_US", us, 0, 60000000)
        if ms and us != ms * 1000:
            raise ValueError("Conflicting TX_INTERVAL_MS and TX_INTERVAL_US")
    else:
        us = (ms or 10) * 1000
    minimum = minimum_interval(values["APP_PAYLOAD_SIZE"])
    if us and us < minimum:
        raise ValueError(f"TX_INTERVAL_US={us} infeasible: minimum {minimum} us "
                         "(packet airtime + 20 us handoff budget), or 0 for max mode")
    values.update(TX_INTERVAL_US=us, TX_INTERVAL_MS=us // 1000)
    if image_mode:
        if values["APP_PAYLOAD_SIZE"] != 240 or values["TX_PACKET_COUNT"] != 434 or us > 3000:
            raise ValueError("Image mode requires payload 240, packet count 434 and interval <= 3000 us")
        values["IMAGE_MODE"] = 1
        values["IMAGE_CONTROL_PROFILE"] = CONTROL_PROFILES.index(control)
    return values

def metadata(values):
    result = {**{field: values[name] for name, field in FIELDS.items()}, "tx_power_dbm": 0}
    if values.get("IMAGE_MODE"):
        result["mode"] = "image"
        result["control_profile"] = CONTROL_PROFILES[values["IMAGE_CONTROL_PROFILE"]]
    return result

def write_config(path, environ, invalidate=False):
    values = configuration(environ)
    content = "/* Generated by scripts/configure.py; do not edit. */\n"
    content += "".join(f"#define {name} {value}\n" for name, value in values.items())
    path = Path(path)
    if not path.exists() or path.read_text() != content:
        if invalidate:
            # macOS Make 3.81 can compare mtimes at whole-second resolution.
            # Explicitly invalidate only our generated role products on changes;
            # otherwise a rapid rebuild can silently retain the previous setup.
            for role in ("tx", "rx"):
                for suffix in ("elf", "bin", "uf2", "uf2.json", "map"):
                    (path.parent / f"{role}.{suffix}").unlink(missing_ok=True)
                for pattern in ("*.o", "*.d"):
                    for product in (path.parent / role).rglob(pattern):
                        product.unlink()
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    return values

if __name__ == "__main__":
    try:
        write_config(sys.argv[1], os.environ, invalidate=True)
    except ValueError as exc:
        sys.exit(f"Experiment configuration: {exc}")
